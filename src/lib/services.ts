export function buildRequest(selected: string[], comment: string): string {
  const lines = ["Здравствуйте! Хочу оставить заявку."];
  if (selected.length) {
    lines.push("", "Услуги:", ...selected.map((x) => `• ${x}`));
  }
  if (comment.trim()) lines.push("", `Комментарий: ${comment.trim()}`);
  return lines.join("\n");
}
