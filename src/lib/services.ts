const priceByName = new Map<string, string>(
  CATALOG.flatMap((c) => c.groups.flatMap((g) => g.items)).map((x) => [x.name, x.price]),
);

export function priceFor(name: string): string | undefined {
  return priceByName.get(name);
}

export function buildRequest(selected: string[], comment: string): string {
  const lines = ["Здравствуйте! Хочу оставить заявку."];
  if (selected.length) {
    lines.push("", "Услуги:", ...selected.map((x) => `• ${x} (${priceFor(x) ?? "цена по консультации"})`));
  }
  if (comment.trim()) lines.push("", `Комментарий: ${comment.trim()}`);
  return lines.join("\n");
}
